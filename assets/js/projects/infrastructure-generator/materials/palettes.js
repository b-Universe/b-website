export function matGetEraPalette(eraStyle = 'modern_municipal', wear = 0.15) {
  const base = INFRA_PALETTES[eraStyle] || INFRA_PALETTES.modern_municipal;
  const w = infraClamp(wear, 0, 1);
  if (w <= 0.05) return { ...base };
  return {
    ...base,
    asphalt: infraMixHex(base.asphalt, '#4b4844', w * 0.25),
    concrete: infraDarkenHex(base.concrete, w * 0.14),
    sidewalk: infraDarkenHex(base.sidewalk, w * 0.12),
    stripe_white: infraMixHex(base.stripe_white, base.asphalt, w * 0.3),
    stripe_yellow: infraMixHex(base.stripe_yellow, base.asphalt, w * 0.25),
    pier_concrete: infraDarkenHex(base.pier_concrete, w * 0.16),
    verge_grass: infraLightenHex(base.verge_grass, w * 0.06),
    rail_steel: infraMixHex(base.rail_steel, base.rail_rust, w * 0.45),
    steel_structure: infraMixHex(base.steel_structure, '#4d3e34', w * 0.22)
  };
}
