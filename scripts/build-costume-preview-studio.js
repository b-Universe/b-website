const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const SRC_DIR = path.join(ROOT, 'assets', 'js', 'projects', 'costume-preview-studio');
const OUT_FILE = path.join(ROOT, 'assets', 'js', 'projects', 'costume-preview-studio.js');

const moduleOrder = [
  'config.js',
  'utils.js',
  'identkit-data.js',
  'textures.js',
  'geometry-core.js',
  'hats.js',
  'costumes.js',
  'rig-inspector.js',
  'game-adapter.js',
  'studio.js',
  'ui.js',
  'index.js'
];

function stripModuleSyntax(source) {
  let code = String(source || '').replace(/^\uFEFF/, '').replace(/\r\n/g, '\n');
  code = code.replace(/^import\s+(?:[\s\S]*?\bfrom\s+)?['"][^'"]+['"];?\s*\n?/gm, '');
  code = code.replace(/^export\s*\{[\s\S]*?\}(?:\s*from\s*['"][^'"]+['"])?;?\s*\n?/gm, '');
  code = code.replace(/^export\s+default\s+/gm, '');
  code = code.replace(/^export\s+(?=(?:async\s+)?function\b|const\b|let\b|var\b|class\b)/gm, '');
  return code.trim();
}

function buildBundle() {
  const chunks = [
    '// B Remastered - 3D Costume Preview Studio Bundle',
    '// Auto-generated by scripts/build-costume-preview-studio.js',
    '(function () {',
    "  'use strict';"
  ];

  for (const rel of moduleOrder) {
    const abs = path.join(SRC_DIR, rel);
    if (!fs.existsSync(abs)) {
      throw new Error(`Missing source module: ${rel}`);
    }
    const cleaned = stripModuleSyntax(fs.readFileSync(abs, 'utf8'));
    chunks.push(`\n  // --- Module: ${rel} ---`);
    chunks.push(cleaned);
  }

  chunks.push('\n})();\n');
  const output = chunks.join('\n');

  // Verify bundled syntax and absence of duplicate top-level bindings
  new Function(output);

  fs.writeFileSync(OUT_FILE, output, 'utf8');
  console.log(`Built ${path.relative(ROOT, OUT_FILE)} (${Buffer.byteLength(output, 'utf8')} bytes, ${moduleOrder.length} modules)`);
  return { outFile: OUT_FILE, byteLength: Buffer.byteLength(output, 'utf8'), moduleCount: moduleOrder.length };
}

if (require.main === module) {
  buildBundle();
}

module.exports = { buildBundle, moduleOrder };
