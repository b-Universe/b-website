const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const SRC_DIR = path.join(ROOT, 'assets', 'js', 'projects', 'city-vehicle-generator');
const OUT_FILE = path.join(ROOT, 'assets', 'js', 'projects', 'city-vehicle-generator.js');

const moduleOrder = [
  'utils.js',
  'core/archetypes.js',
  'config.js',
  'core/layout.js',
  'core/blueprints.js',
  'materials/palettes.js',
  'materials/materials.js',
  'geometry/primitives.js',
  'geometry/chassis.js',
  'geometry/wheels.js',
  'geometry/body.js',
  'geometry/doors-windows.js',
  'geometry/details.js',
  'geometry/vehicle.js',
  'studio/preview.js',
  'studio/export.js',
  'studio/controls.js',
  'index.js'
];

function stripModuleSyntax(source) {
  let code = String(source || '').replace(/^\uFEFF/, '').replace(/\r\n/g, '\n');

  // Remove ES import statements (single-line or multi-line)
  code = code.replace(/^import\s+(?:[\s\S]*?\bfrom\s+)?['"][^'"]+['"];?\s*\n?/gm, '');

  // Remove re-export blocks like: export { foo, bar };
  code = code.replace(/^export\s*\{[\s\S]*?\}(?:\s*from\s*['"][^'"]+['"])?;?\s*\n?/gm, '');

  // Strip export keyword from declarations
  code = code.replace(/^export\s+default\s+/gm, '');
  code = code.replace(/^export\s+(?=(?:async\s+)?function\b|const\b|let\b|var\b|class\b)/gm, '');

  return code.trim();
}

function buildBundle() {
  const chunks = [
    '// B Remastered Procedural 3d City Vehicles Generator Bundle',
    '// Auto-generated by scripts/build-city-vehicle-generator.js',
    '(function () {',
    "  'use strict';"
  ];

  for (const rel of moduleOrder) {
    const abs = path.join(SRC_DIR, rel);
    if (!fs.existsSync(abs)) {
      throw new Error(`Missing source module: ${rel}`);
    }
    const raw = fs.readFileSync(abs, 'utf8');
    const cleaned = stripModuleSyntax(raw);
    chunks.push(`\n  // --- Module: ${rel} ---`);
    chunks.push(cleaned);
  }

  chunks.push('\n})();\n');
  const output = chunks.join('\n');

  // Verify bundled syntax and absence of duplicate top-level declarations
  new Function(output);

  fs.writeFileSync(OUT_FILE, output, 'utf8');
  console.log(`Built ${path.relative(ROOT, OUT_FILE)} (${Buffer.byteLength(output, 'utf8')} bytes, ${moduleOrder.length} modules)`);
}

buildBundle();
